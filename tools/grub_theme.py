#!/usr/bin/env python3
"""Builds the Yggdrasil GRUB boot-menu theme.

    python3 tools/grub_theme.py SVGDIR OUTDIR

SVGDIR is where art.py wrote its SVGs (render.sh's temp dir). OUTDIR gets
theme.txt, the background, the 9-slice frame pieces and (when grub-mkfont or
grub2-mkfont is installed) the .pf2 fonts. The fonts are committed to the repo,
so a machine without grub-mkfont just keeps the existing ones.
"""
import os
import shutil
import subprocess
import sys

from PIL import Image, ImageDraw, ImageFilter

NIGHT = (11, 18, 32)
GOLD = (200, 162, 90)
GOLD_HI = (236, 208, 143)
BONE = (232, 220, 196)
FROST = (143, 196, 224)
W, H = 1920, 1080
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUNIC_TTF = os.path.join(ROOT, "files/system/usr/share/fonts/yggdrasil/YggdrasilRunic.ttf")

