def rsvg(svg, out, w=None, h=None):
    cmd = ["rsvg-convert", svg, "-o", out]
    if w:
        cmd += ["-w", str(w)]
    if h:
        cmd += ["-h", str(h)]
    subprocess.run(cmd, check=True)
    return Image.open(out).convert("RGBA")


def background(svgdir, out, tmp):
    # the fjord at dusk, pushed down into the dark so the menu reads clearly
    fj = rsvg(os.path.join(svgdir, "wall-fjord.svg"), os.path.join(tmp, "fj.png"), W, H)
    bg = Image.new("RGBA", (W, H), NIGHT + (255,))
    bg = Image.blend(bg, fj, 0.38)
    # a soft dark band behind the menu
    shade = Image.new("L", (W, H), 0)
    ImageDraw.Draw(shade).rounded_rectangle((W // 2 - 520, 420, W // 2 + 520, 1000), 60, fill=150)
    shade = shade.filter(ImageFilter.GaussianBlur(60))
    bg = Image.composite(Image.new("RGBA", (W, H), NIGHT + (255,)), bg, shade)
    # emblem and the name in runes above the menu
    logo = rsvg(os.path.join(svgdir, "logo.svg"), os.path.join(tmp, "logo.png"), 300, 300)
    bg.alpha_composite(logo, (W // 2 - 150, 70))
    name = rsvg(os.path.join(svgdir, "name-runes.svg"), os.path.join(tmp, "name.png"), h=54)
    bg.alpha_composite(name, (W // 2 - name.width // 2, 395))
    bg.convert("RGB").save(out, optimize=True)


def nine(out, prefix, size, radius, fill, border, bw):
    """Draws a rounded box and cuts it into GRUB's 9 pieces (nw n ne w c e sw s se)."""
    s = size * 3
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle((0, 0, s - 1, s - 1), radius, fill=fill,
                                          outline=border, width=bw)
    names = [["nw", "n", "ne"], ["w", "c", "e"], ["sw", "s", "se"]]
    for r in range(3):
        for c in range(3):
            img.crop((c * size, r * size, (c + 1) * size, (r + 1) * size)).save(
                os.path.join(out, f"{prefix}_{names[r][c]}.png"))


def fonts(out):
    mk = shutil.which("grub2-mkfont") or shutil.which("grub-mkfont")
    if not mk:
        print("grub-mkfont not found: keeping the committed .pf2 fonts")
        return
    for size in (24,):
        subprocess.run([mk, "-s", str(size), "-n", "Yggdrasil Runic", "-o",
                        os.path.join(out, f"yggdrasil-runic-{size}.pf2"), RUNIC_TTF], check=True)
    dejavu = next((p for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                               "/usr/share/fonts/dejavu-sans-fonts/DejaVuSans.ttf",
                               "/usr/share/fonts/dejavu/DejaVuSans.ttf") if os.path.exists(p)), None)
    if dejavu:
        for size in (16, 18):
            subprocess.run([mk, "-s", str(size), "-r", "0x20-0x7E,0xA0-0xFF,0x2190-0x2193,0x2022-0x2022",
                            "-o", os.path.join(out, f"dejavu-sans-{size}.pf2"), dejavu], check=True)


def main(svgdir, out):
    os.makedirs(out, exist_ok=True)
    tmp = os.path.join(out, ".tmp")
    os.makedirs(tmp, exist_ok=True)
    background(svgdir, os.path.join(out, "background.png"), tmp)
    shutil.rmtree(tmp)
    nine(out, "menu", 16, 14, NIGHT + (215,), GOLD + (255,), 2)        # menu panel
    nine(out, "select", 12, 8, (200, 162, 90, 60), GOLD_HI + (255,), 2)  # highlighted entry
    nine(out, "term", 10, 6, NIGHT + (245,), GOLD + (255,), 2)         # console / edit box
    nine(out, "thumb", 2, 2, GOLD + (255,), GOLD + (255,), 1)          # scrollbar thumb
    nine(out, "bar", 2, 2, (42, 47, 54, 255), (42, 47, 54, 255), 1)    # countdown track
    nine(out, "barhi", 2, 2, GOLD + (255,), GOLD + (255,), 1)          # countdown fill
    with open(os.path.join(out, "theme.txt"), "w") as f:
        f.write(THEME)
    fonts(out)
    print("wrote GRUB theme to", out)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
